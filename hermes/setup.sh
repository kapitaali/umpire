#!/usr/bin/env bash
# hermes/setup.sh — discover executables and directories for the umpire MCP
# integration, then write a sourced env file for Hermes configuration.
#
# Usage:
#   cd /path/to/umpire
#   ./hermes/setup.sh
#   source ~/.hermes/umpire-env.sh
#   hermes config set mcp_servers.umpire.command "$HERMES_PYTHON"
#   hermes config set mcp_servers.umpire.args "[\"$UMPIRE_MCP_SERVER\"]"
#   hermes config set mcp_servers.umpire.env.UMPIRE_SERVER_URL "$UMPIRE_SERVER_URL"
#   hermes config set mcp_servers.umpire.env.UMPIRE_LEDGER_DIR "$UMPIRE_LEDGER_DIR"
#   hermes config set mcp_servers.umpire.env.UMPIRE_PIN "$UMPIRE_PIN"
#   hermes config set mcp_servers.umpire.env.UMPIRE_SEED "$UMPIRE_SEED"
#   hermes gateway restart
#
# Or just source the env file and add the config block manually.

set -euo pipefail

UMPIRE_REPO="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
ENV_FILE="${HOME:-$HOME}/.hermes/umpire-env.sh"

mkdir -p "$(dirname "$ENV_FILE")"

# ---------------------------------------------------------------
# 1. Discover Hermes Python interpreter
# ---------------------------------------------------------------
HERMES_PYTHON=""

# a) hermes config may already tell us
if command -v hermes >/dev/null 2>&1; then
    HERMES_PYTHON="$(hermes config get python.interpreter 2>/dev/null || true)"
fi

# b) Common Hermes tool locations
if [[ -z "$HERMES_PYTHON" || ! -x "$HERMES_PYTHON" ]]; then
    for d in "$HOME/.hermes/tools/python-"*/bin/python; do
        if [[ -x "$d" ]]; then
            HERMES_PYTHON="$d"
            break
        fi
    done
fi

# c) Fall back to system python3
if [[ -z "$HERMES_PYTHON" || ! -x "$HERMES_PYTHON" ]]; then
    if command -v python3 >/dev/null 2>&1; then
        HERMES_PYTHON="$(command -v python3)"
    elif command -v python >/dev/null 2>&1; then
        HERMES_PYTHON="$(command -v python)"
    fi
fi

if [[ -z "$HERMES_PYTHON" || ! -x "$HERMES_PYTHON" ]]; then
    echo "ERROR: could not find a Python interpreter for Hermes" >&2
    exit 1
fi

echo "Hermes Python: $HERMES_PYTHON"

# ---------------------------------------------------------------
# 2. Discover MCP server path (this repo)
# ---------------------------------------------------------------
# the server lives at the repo root (stdlib-only, no MCP SDK)
UMPIRE_MCP_SERVER="$UMPIRE_REPO/mcp_server.py"
if [[ ! -f "$UMPIRE_MCP_SERVER" ]]; then
    echo "ERROR: MCP server not found at $UMPIRE_MCP_SERVER" >&2
    exit 1
fi
echo "MCP server: $UMPIRE_MCP_SERVER"

# ---------------------------------------------------------------
# 3. Discover llama-server binary
# ---------------------------------------------------------------
LLAMA_SERVER=""
for d in \
    "$UMPIRE_REPO/runners/src/build/bin/llama-server" \
    "$HOME/Documents/umpire/runners/src/build/bin/llama-server" \
    "$HOME/.local/bin/llama-server" \
    /usr/local/bin/llama-server \
    /usr/bin/llama-server ; do
    if [[ -x "$d" ]]; then
        LLAMA_SERVER="$d"
        break
    fi
done

if [[ -z "$LLAMA_SERVER" ]]; then
    echo "WARNING: llama-server binary not found" >&2
    echo "  Build it: cd runners && cmake -S . -B build -DGGML_NATIVE=ON && cmake --build build --config Release" >&2
else
    echo "llama-server: $LLAMA_SERVER"
fi

# ---------------------------------------------------------------
# 4. Discover ctxvm replay binary (optional, for replay tool)
# ---------------------------------------------------------------
CTXVM_REPLAY_BIN=""
for d in \
    "$HOME/Documents/ctxvm/rust/target/debug/replay" \
    "$HOME/Documents/ctxvm/rust/target/release/replay" \
    "$HOME/.local/bin/ctxvm-replay" \
    /usr/local/bin/ctxvm-replay ; do
    if [[ -x "$d" ]]; then
        CTXVM_REPLAY_BIN="$d"
        break
    fi
done

if [[ -z "$CTXVM_REPLAY_BIN" ]]; then
    echo "WARNING: ctxvm replay binary not found (replay tool will error at runtime)" >&2
    echo "  Build it: cd Documents/ctxvm/rust && cargo build --release -p ctxvm-conformance" >&2
else
    echo "ctxvm replay: $CTXVM_REPLAY_BIN"
fi

# ---------------------------------------------------------------
# 5. Write env file
# ---------------------------------------------------------------
cat > "$ENV_FILE" <<EOF
# Auto-generated by hermes/setup.sh — do not edit by hand.
# Re-run ./hermes/setup.sh to refresh after moving repos or reinstalling Hermes.

export UMPIRE_REPO="$UMPIRE_REPO"
export HERMES_PYTHON="$HERMES_PYTHON"
export UMPIRE_MCP_SERVER="$UMPIRE_MCP_SERVER"
export UMPIRE_PYTHON="${UMPIRE_PYTHON:-$HERMES_PYTHON}"
export LLAMA_SERVER="$LLAMA_SERVER"
export CTXVM_REPLAY_BIN="$CTXVM_REPLAY_BIN"

export UMPIRE_SERVER_URL="${UMPIRE_SERVER_URL:-http://127.0.0.1:8081}"
export UMPIRE_LEDGER_DIR="${UMPIRE_LEDGER_DIR:-$HOME/.local/state/umpire/ledgers}"
export UMPIRE_PIN="${UMPIRE_PIN:-qwen3-1.7b}"
export UMPIRE_SEED="${UMPIRE_SEED:-7}"
export UMPIRE_TIMEOUT="${UMPIRE_TIMEOUT:-300}"
export UMPIRE_LABELS="${UMPIRE_LABELS:-billing,other,sales,technical}"
EOF

echo ""
echo "Environment file written: $ENV_FILE"
echo ""
echo "Next steps:"
echo "  1. source $ENV_FILE"
echo "  2. pip install jsonschema>=4  (needed by validate + replay; set UMPIRE_PYTHON to any interpreter that has it)"
echo "  3. Start llama-server:"
echo "     $LLAMA_SERVER -m models/Qwen3-1.7B-Q8_0.gguf -c 2048 --host 127.0.0.1 --port 8081 --threads 4"
echo "  4. Configure Hermes MCP server:"
echo "     hermes config set mcp_servers.umpire.command \"\$HERMES_PYTHON\""
echo "     hermes config set mcp_servers.umpire.args \"[\\\"$UMPIRE_MCP_SERVER\\\"]\""
echo "     hermes config set mcp_servers.umpire.env.UMPIRE_SERVER_URL \"\$UMPIRE_SERVER_URL\""
echo "     hermes config set mcp_servers.umpire.env.UMPIRE_LEDGER_DIR \"\$UMPIRE_LEDGER_DIR\""
echo "     hermes config set mcp_servers.umpire.env.UMPIRE_PIN \"\$UMPIRE_PIN\""
echo "     hermes config set mcp_servers.umpire.env.UMPIRE_SEED \"\$UMPIRE_SEED\""
echo "  5. hermes gateway restart"
echo ""
echo "  6. hermes chat -q \"Call mcp_umpire_pins and report the available pins.\""
