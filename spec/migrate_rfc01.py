#!/usr/bin/env python3
"""Migrate umpire's decision ledgers to the xCABI RFC-0.1 profile.

Two changes, both optional in the schema and both required for umpire's own
intent to be readable by an RFC-0.1 consumer:

  R0  session.open gains `schemaVersion: "0.1"` — the version boundary. A trace
      without it is a v0 trace, and v0 has no typed re-execution.
  R1  a deliberate re-decide (`page.fault` for a state the ledger already holds)
      is `intentional_rerun`, not `tool_recall`. `tool_recall` stays reserved for
      a page the agent re-fetched because it had been paged out; umpire never
      pages anything out, so every fault it emits is deliberate.

The page-table baseline is re-derived for each ledger, because the derived table
records the fault source.

Fixtures generated by `spec/make_fixtures.py` are regenerated from the generator
instead; this script exists for the captured fixtures (`ab-demo`, `live-demo`)
that have no generator, and as the audit trail for what changed.

Usage:
  python3 spec/migrate_rfc01.py            # all fixtures, in place
  python3 spec/migrate_rfc01.py --check    # report what would change, write nothing
"""

import json
import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).parent))

from ledger_tools import derive_page_table, render_page_table  # noqa: E402

FIXTURES = pathlib.Path(__file__).parent.parent / "fixtures"
NAMES = ("ab-demo", "intent-router", "live-demo", "support-triage")


def migrate_lines(ledger_text):
    """Return (new_text, n_declares_touched, n_faults_retyped)."""
    events = []
    faults = 0
    for line in ledger_text.splitlines():
        if not line:
            continue
        event = json.loads(line)
        if event.get("type") == "session.open":
            event.setdefault("schemaVersion", "0.1")
        elif event.get("type") == "page.fault" and event.get("source") == "tool_recall":
            event["source"] = "intentional_rerun"
            faults += 1
        events.append(event)
    new_text = "".join(json.dumps(e) + "\n" for e in events)
    return new_text, faults


def main() -> int:
    check = "--check" in sys.argv
    rc = 0
    for name in NAMES:
        ledger_path = FIXTURES / f"{name}.ledger.jsonl"
        records_path = FIXTURES / f"{name}.records.jsonl"
        table_path = FIXTURES / f"{name}.page-table.json"
        if not ledger_path.exists():
            print(f"{name}: ledger missing, skipped")
            continue
        old = ledger_path.read_text()
        new, faults = migrate_lines(old)
        table = derive_page_table(new.splitlines(keepends=True),
                                  records_path.read_text().splitlines(keepends=True))
        new_table = render_page_table(table).decode("utf-8")
        ledger_changed = new != old
        table_changed = new_table != table_path.read_text()
        print(f"{name}: faults_retyped={faults} ledger_changed={ledger_changed} "
              f"page_table_changed={table_changed}")
        if check:
            if ledger_changed or table_changed:
                rc = 1
            continue
        if ledger_changed:
            ledger_path.write_text(new)
        if table_changed:
            table_path.write_text(new_table)
    return rc


if __name__ == "__main__":
    sys.exit(main())
